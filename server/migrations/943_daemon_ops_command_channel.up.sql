-- RUYI-645: daemon ops command channel (read-only v1) — command ledger and
-- node service inventory.
--
-- daemon_ops_command is one row per submitted read-only command (seven-kind
-- whitelist, see server/pkg/opskind). Lifecycle: pending → claimed →
-- succeeded|failed|rejected, with the bypass terminal states expired (never
-- claimed before the pending TTL: the node was offline; commands are never
-- re-dispatched, by assertion 5) and timeout (claimed but no receipt within
-- the lease). lease_epoch is the receipt-ownership token: a result POST must
-- echo the epoch the server handed out at claim time, so a stale or
-- mismatched daemon receipt can never overwrite another generation's row.
--
-- Like audit_event (926) there are no foreign keys here by design: rows are
-- operational evidence and must survive the deletion of the runtime or
-- member they mention; workspace teardown sweeps them explicitly through the
-- application-layer deletion graph.
--
-- The ids are generated by the application (uuid), matching the
-- daemon-token/audit insert style where the server owns identity.
CREATE TABLE daemon_ops_command (
    id UUID PRIMARY KEY,
    workspace_id UUID NOT NULL,
    runtime_id UUID NOT NULL,
    -- daemon_id is an evidence copy of agent_runtime.daemon_id at submit
    -- time; the claim path re-reads the runtime, this column only keeps the
    -- row interpretable after the runtime is deleted.
    daemon_id TEXT NOT NULL DEFAULT '',
    kind TEXT NOT NULL,
    -- Typed-slot arguments (e.g. {"unit":"nginx.service","lines":100});
    -- validated against the shared opskind registry on both ends.
    args JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN
        ('pending', 'claimed', 'succeeded', 'failed', 'rejected', 'timeout', 'expired')),
    timeout_s INT NOT NULL DEFAULT 30 CHECK (timeout_s >= 1 AND timeout_s <= 300),
    -- Receipt-ownership generation. Bumped inside the atomic claim UPDATE;
    -- result POSTs must echo it.
    lease_epoch BIGINT NOT NULL DEFAULT 0,
    claimed_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    exit_code INT,
    -- {"stdout":"...","stderr":"...","truncated":true}; total content is
    -- capped at 256KB by the write path. NULL until a terminal receipt.
    result JSONB,
    reject_reason TEXT,
    submitted_by_type TEXT NOT NULL CHECK (submitted_by_type IN ('member', 'agent')),
    submitted_by_id UUID NOT NULL,
    -- Client-supplied idempotency key; uniqueness per runtime is enforced by
    -- the partial unique index below for the 10-minute idempotency window
    -- (the window expiry path NULLs the key instead of deleting the row).
    submission_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Idempotency (assertion 3): the same submission_key on one runtime can only
-- ever reference one non-archived command.
CREATE UNIQUE INDEX idx_daemon_ops_command_submission_key
    ON daemon_ops_command (runtime_id, submission_key)
    WHERE submission_key IS NOT NULL;

-- History list per runtime, newest first (Web command history panel).
-- New tables created in this same migration are empty at index-build time —
-- plain CREATE INDEX is safe here; the CONCURRENTLY rule (AGENTS.md) applies
-- to index builds on existing populated tables (same reasoning as
-- 926_activity_audit.up.sql).
CREATE INDEX idx_daemon_ops_command_runtime_created
    ON daemon_ops_command (runtime_id, created_at DESC);

-- Claim/sweep scans only touch in-flight rows; the partial index keeps the
-- heartbeat-claim UPDATE and the periodic sweeps on the hot subset.
CREATE INDEX idx_daemon_ops_command_inflight
    ON daemon_ops_command (status, claimed_at)
    WHERE status IN ('pending', 'claimed');

-- daemon_service_inventory is the latest service inventory a daemon
-- reported for its machine (design §5). One row per daemon (PK daemon_id —
-- machine fact, not workspace data): collect_status distinguishes "collected
-- fine" (ok) from "the collector could not run" (unavailable, with error and
-- an empty services array), so the Web surface can render an unavailable
-- state instead of an empty list or zero-filled rows (assertion 2).
-- last_report_at / last_success_at are deliberately separate: the first
-- advances on every report attempt, the second only on a successful
-- collection, making collection staleness directly visible.
CREATE TABLE daemon_service_inventory (
    daemon_id TEXT PRIMARY KEY,
    collect_status TEXT NOT NULL DEFAULT 'unavailable' CHECK (collect_status IN ('ok', 'unavailable')),
    services JSONB NOT NULL DEFAULT '[]'::jsonb,
    error TEXT,
    last_report_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_success_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
